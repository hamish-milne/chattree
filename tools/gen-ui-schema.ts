/**
 * Writes `ui/fixtures/harness-schema.ts`: the JSON Schema of `harness.yml` exactly as `configJsonSchema` produces it,
 * for the mock extension and the tests (the UI bundle cannot import the harness). `test/ui/harness-schema.test.ts`
 * fails when this file has fallen behind the harness; run `node --no-warnings tools/gen-ui-schema.ts` and format.
 */
import { writeFile } from "node:fs/promises";
import { configJsonSchema } from "../harness/config-schema.ts";
import { defaultRegistry } from "../providers/index.ts";

const schema: unknown = JSON.parse(JSON.stringify(configJsonSchema(defaultRegistry())));
const text = `/** The JSON Schema of harness.yml, generated by tools/gen-ui-schema.ts; do not edit by hand. */
export const harnessSchema: Record<string, unknown> = ${JSON.stringify(schema, null, 2)};
`;
await writeFile(new URL("../ui/fixtures/harness-schema.ts", import.meta.url), text);
