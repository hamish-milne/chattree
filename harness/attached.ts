/**
 * Repositories attached to a thread: git submodules of the thread's worktree, where the production code lives while the thread's own
 * repository is the scratch space and the transcript (ADR 38). The parent records a submodule as one commit id and nothing of what is
 * uncommitted inside it, so rewinding the thread could not bring the code back. This module closes that gap:
 *
 * - `syncAttached` runs before each snapshot of the thread's worktree. For every attached repository it records the commit and the
 *   branch checked out, and when the working tree differs from HEAD, a snapshot commit of it (tracked, modified and untracked files,
 *   not ignored ones). The result is written to `attached.yml`, a tracked file, so the record rewinds and forks with the files and a
 *   change that is only uncommitted still makes the thread's own snapshot happen.
 * - `restoreAttached` is the other direction: it puts each repository back as `attached.yml` says.
 *
 * A snapshot commit is an ordinary git commit: its parents are the repository's HEAD and the previous snapshot of the thread, and the
 * ref `refs/chattree/snapshots/<thread>` (in the attached repository) keeps the whole chain from being collected. The tree is built in
 * a private index per thread, so the repository's own index and its stat cache are untouched and a large repository is not read again
 * at every snapshot. Nothing here moves the person's branch except `restoreAttached`, which keeps what it leaves behind under
 * `refs/chattree/undone/<thread>/`.
 */
import { parse, stringify } from "yaml";
import type { Git, Identity } from "../src/index.ts";
import type { Host } from "../src/host.ts";

/** The record, at the top of the thread's worktree. Generated: the harness rewrites it from the repositories' state. */
export const ATTACHED_FILE = "attached.yml";
export const SNAPSHOT_REFS = "refs/chattree/snapshots";
export const UNDONE_REFS = "refs/chattree/undone";

const HEX = /^[0-9a-f]{40}([0-9a-f]{24})?$/;
const enc = new TextEncoder();
const dec = new TextDecoder();

export class AttachedError extends Error {
  override readonly name = "AttachedError";
}

/** What is recorded about one attached repository. */
export interface AttachedState {
  /** Where it is, relative to the thread's worktree, `/`-separated. */
  path: string;
  /** The branch checked out; none when HEAD is detached. */
  branch?: string;
  /** HEAD. */
  base: string;
  /** A commit holding the uncommitted state on top of `base`; none when the working tree is as HEAD has it. */
  snapshot?: string;
}

export function formatAttached(states: readonly AttachedState[]): string {
  if (states.length === 0) return "";
  const items = [...states]
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
    .map((s) => ({
      path: s.path,
      ...(s.branch === undefined ? {} : { branch: s.branch }),
      base: s.base,
      ...(s.snapshot === undefined ? {} : { snapshot: s.snapshot }),
    }));
  return `# Repositories attached to this thread. Generated by chattree from their state: edits are overwritten.\n${stringify(items)}`;
}

/** Read the record. A malformed one is an error: restoring from half of it would put code in the wrong state. */
export function parseAttached(text: string): AttachedState[] {
  let doc: unknown;
  try {
    doc = parse(text);
  } catch (e) {
    throw new AttachedError(`${ATTACHED_FILE} is not valid YAML: ${e instanceof Error ? e.message : String(e)}`);
  }
  if (doc === null || doc === undefined) return [];
  if (!Array.isArray(doc)) throw new AttachedError(`${ATTACHED_FILE} must be a list`);
  return doc.map((raw: unknown, i) => {
    const o: Record<string, unknown> = typeof raw === "object" && raw !== null ? Object.fromEntries(Object.entries(raw)) : {};
    const path = o["path"];
    const base = o["base"];
    const branch = o["branch"];
    const snapshot = o["snapshot"];
    if (typeof path !== "string" || path === "" || path.startsWith("/") || path.split("/").includes(".."))
      throw new AttachedError(`${ATTACHED_FILE} entry ${i + 1}: path must be a relative path inside the worktree`);
    if (typeof base !== "string" || !HEX.test(base)) throw new AttachedError(`${ATTACHED_FILE} entry ${i + 1}: base must be a commit id`);
    if (branch !== undefined && (typeof branch !== "string" || branch === ""))
      throw new AttachedError(`${ATTACHED_FILE} entry ${i + 1}: branch must be a name`);
    if (snapshot !== undefined && (typeof snapshot !== "string" || !HEX.test(snapshot)))
      throw new AttachedError(`${ATTACHED_FILE} entry ${i + 1}: snapshot must be a commit id`);
    return { path, base, ...(branch === undefined ? {} : { branch }), ...(snapshot === undefined ? {} : { snapshot }) };
  });
}

/** The submodules of `git`'s worktree that are checked out: the paths, and the commit the parent records for each. */
export async function discoverAttached(host: Host, git: Git): Promise<{ path: string; commit: string }[]> {
  const out = await git.run(["ls-files", "-s", "-z"], { readOnly: true });
  const found: { path: string; commit: string }[] = [];
  for (const rec of dec.decode(out.stdout).split("\u0000")) {
    if (!rec.startsWith("160000 ")) continue;
    const tab = rec.indexOf("\t");
    const path = rec.slice(tab + 1);
    // A submodule that was never initialised is an empty directory: nothing is attached there yet.
    if ((await host.fs.stat(host.path.join(git.cwd, path, ".git"))) === undefined) continue;
    found.push({ path, commit: rec.slice(7, tab).split(" ")[1] ?? "" });
  }
  return found.sort((a, b) => (a.path < b.path ? -1 : 1));
}

const snapshotRef = (thread: string): string => `${SNAPSHOT_REFS}/${thread}`;

/** The repository's state now, with a snapshot commit when the working tree is not as HEAD has it. */
export async function snapshotRepo(
  host: Host,
  repo: Git,
  path: string,
  thread: string,
  who: Identity,
  previous?: AttachedState,
  date?: string,
): Promise<AttachedState> {
  const head = await repo.revParse("HEAD");
  if (head === undefined) throw new AttachedError(`${path} has no commits`);
  const branch = await repo.currentBranch();
  const state: AttachedState = { path, ...(branch === undefined ? {} : { branch }), base: head };

  const dir = host.path.join(await repo.commonDir(), "chattree");
  await host.fs.mkdir(dir);
  const index = host.path.join(dir, `index-${thread.replace(/[^A-Za-z0-9._-]/g, "_")}`);
  const env = { GIT_INDEX_FILE: index };
  if ((await host.fs.stat(index)) === undefined) await repo.run(["read-tree", head], { env });
  await repo.run(["add", "--all", "--", "."], { env });
  const tree = await repo.text(["write-tree"], { env });
  if (tree === (await repo.treeOf(head))) return state;

  if (previous?.snapshot !== undefined && previous.base === head && (await repo.treeOf(previous.snapshot)) === tree)
    return { ...state, snapshot: previous.snapshot };

  const ref = snapshotRef(thread);
  const tip = await repo.revParse(ref);
  const snapshot = await repo.commitTree(tree, tip === undefined ? [head] : [head, tip], {
    message: `chattree: uncommitted changes of ${thread}`,
    author: who,
    committer: who,
    ...(date === undefined ? {} : { date }),
  });
  await repo.run(["update-ref", ref, snapshot]);
  return { ...state, snapshot };
}

export interface SyncResult {
  states: AttachedState[];
  /** The record was written (it differed from what was there). */
  changed: boolean;
}

/** Record every attached repository's state in `attached.yml`. Call it just before the worktree is snapshotted. */
export async function syncAttached(host: Host, git: Git, thread: string, who: Identity, date?: string): Promise<SyncResult> {
  const file = host.path.join(git.cwd, ATTACHED_FILE);
  const existing = (await host.fs.stat(file)) === undefined ? undefined : dec.decode(await host.fs.read(file));
  let before: AttachedState[] = [];
  try {
    before = existing === undefined ? [] : parseAttached(existing);
  } catch {
    // A damaged record is replaced by the live state; there is nothing in it to keep.
  }
  const states: AttachedState[] = [];
  for (const { path } of await discoverAttached(host, git)) {
    const prev = before.find((s) => s.path === path);
    states.push(await snapshotRepo(host, git.withCwd(host.path.join(git.cwd, path)), path, thread, who, prev, date));
  }
  const text = formatAttached(states);
  if ((existing ?? "") === text) return { states, changed: false };
  if (text === "") await host.fs.remove(file);
  else await host.fs.writeAtomic(file, enc.encode(text));
  return { states, changed: true };
}

export interface RestoreResult {
  path: string;
  /** What the working tree is now: the recorded uncommitted state, only the commit, or not touched. */
  restored: "snapshot" | "base" | "none";
  /** Why it is less than recorded; empty when all of it was restored. */
  warnings: string[];
}

/**
 * Put each recorded repository back: the branch at the recorded commit and the working tree as it was then, uncommitted changes and
 * untracked files included. What is there now is snapshotted first, and commits the branch loses are kept under
 * `refs/chattree/undone/<thread>/`, so nothing is lost at once. A repository that is not checked out or whose commit is missing is
 * left alone and reported.
 */
export async function restoreAttached(
  host: Host,
  git: Git,
  thread: string,
  states: readonly AttachedState[],
  who: Identity,
  date?: string,
): Promise<RestoreResult[]> {
  const results: RestoreResult[] = [];
  for (const s of states) {
    const dir = host.path.join(git.cwd, s.path);
    if ((await host.fs.stat(host.path.join(dir, ".git"))) === undefined) {
      results.push({ path: s.path, restored: "none", warnings: [`${s.path} is not checked out`] });
      continue;
    }
    const repo = git.withCwd(dir);
    const has = async (oid: string): Promise<boolean> => (await repo.objectInfo([`${oid}^{commit}`]))[0] !== undefined;
    if (!(await has(s.base))) {
      results.push({ path: s.path, restored: "none", warnings: [`commit ${s.base.slice(0, 8)} is not in ${s.path}`] });
      continue;
    }
    const warnings: string[] = [];
    let snapshot = s.snapshot;
    if (snapshot !== undefined && !(await has(snapshot))) {
      warnings.push(
        `the uncommitted changes of ${s.path} (${snapshot.slice(0, 8)}) are not in the repository; only its commit is restored`,
      );
      snapshot = undefined;
    }

    await snapshotRepo(host, repo, s.path, thread, who, undefined, date); // keep what is there, in the chain
    await repo.run(["reset", "--hard", "--quiet"]);
    await repo.run(["clean", "-fdq"]);
    const current = await repo.currentBranch();
    if (s.branch === undefined) {
      if (current !== undefined || (await repo.revParse("HEAD")) !== s.base) await repo.run(["checkout", "--detach", "--quiet", s.base]);
    } else {
      const tip = await repo.revParse(`refs/heads/${s.branch}`);
      if (tip !== undefined && tip !== s.base && !(await repo.isAncestor(tip, s.base)))
        await repo.run(["update-ref", `${UNDONE_REFS}/${thread}/${tip.slice(0, 8)}`, tip]);
      await repo.run(["checkout", "--quiet", "-B", s.branch, s.base]);
    }
    if (snapshot !== undefined) {
      await repo.run(["read-tree", "--reset", "-u", `${snapshot}^{tree}`]);
      await repo.run(["reset", "--quiet"]); // the index as HEAD has it: the changes show as the person would have made them
    }
    results.push({ path: s.path, restored: snapshot === undefined ? "base" : "snapshot", warnings });
  }
  return results;
}
