/**
 * Repositories attached to a thread: git submodules of the thread's worktree, where the production code lives while the thread's own
 * repository is the scratch space and the transcript (ADR 38). The parent records a submodule as one commit id and nothing of what is
 * uncommitted inside it, so rewinding the thread could not bring the code back. This module closes that gap:
 *
 * - `syncAttached` runs before each snapshot of the thread's worktree. For every attached repository it records the commit and the
 *   branch checked out, and when the working tree differs from HEAD, a snapshot commit of it (tracked, modified and untracked files,
 *   not ignored ones). The result is written to `attached.yml`, a tracked file, so the record rewinds and forks with the files and a
 *   change that is only uncommitted still makes the thread's own snapshot happen.
 * - `restoreAttached` is the other direction: it puts each repository back as `attached.yml` says.
 *
 * A snapshot commit is an ordinary git commit: its parents are the repository's HEAD and the previous snapshot of the thread, and the
 * ref `refs/chattree/snapshots/<thread>` (in the attached repository) keeps the whole chain from being collected. The tree is built in
 * a private index per thread, so the repository's own index and its stat cache are untouched and a large repository is not read again
 * at every snapshot. Nothing here moves the person's branch except `restoreAttached`, which keeps what it leaves behind under
 * `refs/chattree/undone/<thread>/`.
 */
import { parse, stringify } from "yaml";
import { GitError, type Git, type Identity } from "../src/index.ts";
import type { Host } from "../src/host.ts";

/** The record, at the top of the thread's worktree. Generated: the harness rewrites it from the repositories' state. */
export const ATTACHED_FILE = "attached.yml";
export const SNAPSHOT_REFS = "refs/chattree/snapshots";
export const UNDONE_REFS = "refs/chattree/undone";

const HEX = /^[0-9a-f]{40}([0-9a-f]{24})?$/;
const enc = new TextEncoder();
const dec = new TextDecoder();

export class AttachedError extends Error {
  override readonly name = "AttachedError";
}

/** What is recorded about one attached repository. */
export interface AttachedState {
  /** Where it is, relative to the thread's worktree, `/`-separated. */
  path: string;
  /** The branch checked out; none when HEAD is detached. */
  branch?: string;
  /** HEAD. */
  base: string;
  /** A commit holding the uncommitted state on top of `base`; none when the working tree is as HEAD has it. */
  snapshot?: string;
}

export function formatAttached(states: readonly AttachedState[]): string {
  if (states.length === 0) return "";
  const items = [...states]
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
    .map((s) => ({
      path: s.path,
      ...(s.branch === undefined ? {} : { branch: s.branch }),
      base: s.base,
      ...(s.snapshot === undefined ? {} : { snapshot: s.snapshot }),
    }));
  return `# Repositories attached to this thread. Generated by chattree from their state: edits are overwritten.\n${stringify(items)}`;
}

/** Read the record. A malformed one is an error: restoring from half of it would put code in the wrong state. */
export function parseAttached(text: string): AttachedState[] {
  let doc: unknown;
  try {
    doc = parse(text);
  } catch (e) {
    throw new AttachedError(`${ATTACHED_FILE} is not valid YAML: ${e instanceof Error ? e.message : String(e)}`);
  }
  if (doc === null || doc === undefined) return [];
  if (!Array.isArray(doc)) throw new AttachedError(`${ATTACHED_FILE} must be a list`);
  return doc.map((raw: unknown, i) => {
    const o: Record<string, unknown> = typeof raw === "object" && raw !== null ? Object.fromEntries(Object.entries(raw)) : {};
    const path = o["path"];
    const base = o["base"];
    const branch = o["branch"];
    const snapshot = o["snapshot"];
    if (typeof path !== "string" || path === "" || path.startsWith("/") || path.split("/").includes(".."))
      throw new AttachedError(`${ATTACHED_FILE} entry ${i + 1}: path must be a relative path inside the worktree`);
    if (typeof base !== "string" || !HEX.test(base)) throw new AttachedError(`${ATTACHED_FILE} entry ${i + 1}: base must be a commit id`);
    if (branch !== undefined && (typeof branch !== "string" || branch === ""))
      throw new AttachedError(`${ATTACHED_FILE} entry ${i + 1}: branch must be a name`);
    if (snapshot !== undefined && (typeof snapshot !== "string" || !HEX.test(snapshot)))
      throw new AttachedError(`${ATTACHED_FILE} entry ${i + 1}: snapshot must be a commit id`);
    return { path, base, ...(branch === undefined ? {} : { branch }), ...(snapshot === undefined ? {} : { snapshot }) };
  });
}

/** The submodules of `git`'s worktree that are checked out: the paths, and the commit the parent records for each. */
export async function discoverAttached(host: Host, git: Git): Promise<{ path: string; commit: string }[]> {
  const out = await git.run(["ls-files", "-s", "-z"], { readOnly: true });
  const found: { path: string; commit: string }[] = [];
  for (const rec of dec.decode(out.stdout).split("\u0000")) {
    if (!rec.startsWith("160000 ")) continue;
    const tab = rec.indexOf("\t");
    const path = rec.slice(tab + 1);
    // A submodule that was never initialised is an empty directory: nothing is attached there yet.
    if ((await host.fs.stat(host.path.join(git.cwd, path, ".git"))) === undefined) continue;
    found.push({ path, commit: rec.slice(7, tab).split(" ")[0] ?? "" });
  }
  return found.sort((a, b) => (a.path < b.path ? -1 : 1));
}

const snapshotRef = (thread: string): string => `${SNAPSHOT_REFS}/${thread}`;

/** The repository's state now, with a snapshot commit when the working tree is not as HEAD has it. */
export async function snapshotRepo(
  host: Host,
  repo: Git,
  path: string,
  thread: string,
  who: Identity,
  previous?: AttachedState,
  date?: string,
): Promise<AttachedState> {
  const head = await repo.revParse("HEAD");
  if (head === undefined) throw new AttachedError(`${path} has no commits`);
  const branch = await repo.currentBranch();
  const state: AttachedState = { path, ...(branch === undefined ? {} : { branch }), base: head };

  const dir = host.path.join(await repo.commonDir(), "chattree");
  await host.fs.mkdir(dir);
  const index = host.path.join(dir, `index-${thread.replace(/[^A-Za-z0-9._-]/g, "_")}`);
  const env = { GIT_INDEX_FILE: index };
  const build = async (): Promise<string> => {
    if ((await host.fs.stat(index)) === undefined) await repo.run(["read-tree", head], { env });
    await repo.run(["add", "--all", "--", "."], { env });
    return repo.text(["write-tree"], { env });
  };
  let tree: string;
  try {
    tree = await build();
  } catch (e) {
    // The private index remembers blobs by id and by stat: if the repository has since lost one (a prune), start it again.
    if (!(e instanceof GitError)) throw e;
    await host.fs.remove(index);
    tree = await build();
  }
  const ref = snapshotRef(thread);
  const headTree = await repo.treeOf(head);
  if (tree === headTree) {
    await keepCommit(repo, ref, head, headTree, thread, who, date);
    return state;
  }

  if (previous?.snapshot !== undefined && previous.base === head && (await repo.treeOf(previous.snapshot)) === tree)
    return { ...state, snapshot: previous.snapshot };

  const tip = await repo.revParse(ref);
  const snapshot = await repo.commitTree(tree, tip === undefined ? [head] : [head, tip], {
    message: `chattree: uncommitted changes of ${thread}`,
    author: who,
    committer: who,
    ...(date === undefined ? {} : { date }),
  });
  await repo.run(["update-ref", ref, snapshot]);
  return { ...state, snapshot };
}

/**
 * Keep HEAD reachable. A commit the person or the model made, rebased or reset away is recorded in `attached.yml` and may be needed to
 * rewind, but nothing in the repository need point at it any more. When the chain's tip is not already on top of this HEAD, add an
 * empty commit that is, once per HEAD that has been seen.
 */
async function keepCommit(
  repo: Git,
  ref: string,
  head: string,
  headTree: string,
  thread: string,
  who: Identity,
  date?: string,
): Promise<void> {
  const tip = await repo.revParse(ref);
  if (tip !== undefined && (await repo.revParse(`${tip}^1`)) === head) return;
  const keep = await repo.commitTree(headTree, tip === undefined ? [head] : [head, tip], {
    message: `chattree: ${thread} is at ${head.slice(0, 8)}`,
    author: who,
    committer: who,
    ...(date === undefined ? {} : { date }),
  });
  await repo.run(["update-ref", ref, keep]);
}

export interface SyncResult {
  states: AttachedState[];
  /** The record was written (it differed from what was there). */
  changed: boolean;
}

/** Record every attached repository's state in `attached.yml`. Call it just before the worktree is snapshotted. */
export async function syncAttached(host: Host, git: Git, thread: string, who: Identity, date?: string): Promise<SyncResult> {
  const file = host.path.join(git.cwd, ATTACHED_FILE);
  const existing = (await host.fs.stat(file)) === undefined ? undefined : dec.decode(await host.fs.read(file));
  let before: AttachedState[] = [];
  try {
    before = existing === undefined ? [] : parseAttached(existing);
  } catch {
    // A damaged record is replaced by the live state; there is nothing in it to keep.
  }
  const states: AttachedState[] = [];
  for (const { path } of await discoverAttached(host, git)) {
    const prev = before.find((s) => s.path === path);
    states.push(await snapshotRepo(host, git.withCwd(host.path.join(git.cwd, path)), path, thread, who, prev, date));
  }
  const text = formatAttached(states);
  if ((existing ?? "") === text) return { states, changed: false };
  if (text === "") await host.fs.remove(file);
  else await host.fs.writeAtomic(file, enc.encode(text));
  return { states, changed: true };
}

export interface RestoreResult {
  path: string;
  /** What the working tree is now: the recorded uncommitted state, only the commit, or not touched. */
  restored: "snapshot" | "base" | "none";
  /** Why it is less than recorded; empty when all of it was restored. */
  warnings: string[];
}

/**
 * Put each recorded repository back: the branch at the recorded commit and the working tree as it was then, uncommitted changes and
 * untracked files included. What is there now is snapshotted first, and commits the branch loses are kept under
 * `refs/chattree/undone/<thread>/`, so nothing is lost at once. A repository that is not checked out or whose commit is missing is
 * left alone and reported.
 */
export async function restoreAttached(
  host: Host,
  git: Git,
  thread: string,
  states: readonly AttachedState[],
  who: Identity,
  date?: string,
): Promise<RestoreResult[]> {
  const results: RestoreResult[] = [];
  for (const s of states) {
    const dir = host.path.join(git.cwd, s.path);
    if ((await host.fs.stat(host.path.join(dir, ".git"))) === undefined) {
      results.push({ path: s.path, restored: "none", warnings: [`${s.path} is not checked out`] });
      continue;
    }
    const repo = git.withCwd(dir);
    const has = async (oid: string): Promise<boolean> => (await repo.objectInfo([`${oid}^{commit}`]))[0] !== undefined;
    if (!(await has(s.base))) {
      results.push({ path: s.path, restored: "none", warnings: [`commit ${s.base.slice(0, 8)} is not in ${s.path}`] });
      continue;
    }
    const warnings: string[] = [];
    let snapshot = s.snapshot;
    if (snapshot !== undefined && !(await has(snapshot))) {
      warnings.push(
        `the uncommitted changes of ${s.path} (${snapshot.slice(0, 8)}) are not in the repository; only its commit is restored`,
      );
      snapshot = undefined;
    }

    await snapshotRepo(host, repo, s.path, thread, who, undefined, date); // keep what is there, in the chain
    await repo.run(["reset", "--hard", "--quiet"]);
    await repo.run(["clean", "-fdq"]);
    const current = await repo.currentBranch();
    if (s.branch === undefined) {
      if (current !== undefined || (await repo.revParse("HEAD")) !== s.base) await repo.run(["checkout", "--detach", "--quiet", s.base]);
    } else {
      const tip = await repo.revParse(`refs/heads/${s.branch}`);
      if (tip !== undefined && tip !== s.base && !(await repo.isAncestor(tip, s.base)))
        await repo.run(["update-ref", `${UNDONE_REFS}/${thread}/${tip.slice(0, 8)}`, tip]);
      await repo.run(["checkout", "--quiet", "-B", s.branch, s.base]);
    }
    if (snapshot !== undefined) {
      await repo.run(["read-tree", "--reset", "-u", `${snapshot}^{tree}`]);
      await repo.run(["reset", "--quiet"]); // the index as HEAD has it: the changes show as the person would have made them
    }
    results.push({ path: s.path, restored: snapshot === undefined ? "base" : "snapshot", warnings });
  }
  return results;
}

const attachedAt = async (host: Host, dir: string): Promise<AttachedState[] | { error: string }> => {
  const file = host.path.join(dir, ATTACHED_FILE);
  if ((await host.fs.stat(file)) === undefined) return [];
  try {
    return parseAttached(dec.decode(await host.fs.read(file)));
  } catch (e) {
    return { error: e instanceof Error ? e.message : String(e) };
  }
};

/** What `attached.yml` in a worktree says; empty when it has none, and a warning result when it cannot be read. */
export async function recordedAttached(host: Host, dir: string): Promise<{ states: AttachedState[]; problem?: RestoreResult }> {
  const r = await attachedAt(host, dir);
  if (Array.isArray(r)) return { states: r };
  return { states: [], problem: { path: ATTACHED_FILE, restored: "none", warnings: [r.error] } };
}

/**
 * The branch a thread keeps in an attached repository when the folders trade threads. A branch stays if it is still where the thread left
 * it (or gone) and nobody else has claimed it: two threads cannot have a branch checked out at once, and a thread must not move a branch
 * the person has since moved on. Otherwise the thread is left on a detached HEAD at its commit.
 */
async function codeBranchFor(repo: Git, s: AttachedState, claimed: Set<string>): Promise<string | undefined> {
  if (s.branch === undefined) return undefined;
  const tip = await repo.revParse(`refs/heads/${s.branch}`);
  if ((tip === undefined || tip === s.base) && !claimed.has(s.branch)) {
    claimed.add(s.branch);
    return s.branch;
  }
  return undefined;
}

/**
 * Give a thread's new worktree its own checkout of each attached repository: a linked worktree of the repository in the project
 * folder, on a detached HEAD at the recorded commit with the recorded uncommitted state. (A parent worktree starts with the submodules
 * empty.) The thread starts the branch itself if it is to make commits.
 */
export async function attachCodeWorktrees(
  host: Host,
  git: Git,
  projectDir: string,
  worktree: string,
  thread: string,
  who: Identity,
): Promise<RestoreResult[]> {
  const { states, problem } = await recordedAttached(host, worktree);
  const results: RestoreResult[] = problem === undefined ? [] : [problem];
  const mapped: AttachedState[] = [];
  for (const s of states) {
    const source = git.withCwd(host.path.join(projectDir, s.path));
    const dest = host.path.join(worktree, s.path);
    if ((await host.fs.stat(host.path.join(projectDir, s.path, ".git"))) === undefined) {
      results.push({
        path: s.path,
        restored: "none",
        warnings: [`${s.path} is not checked out in the project folder, so this thread has no copy of it`],
      });
      continue;
    }
    if ((await host.fs.stat(host.path.join(dest, ".git"))) === undefined) {
      if ((await source.objectInfo([`${s.base}^{commit}`]))[0] === undefined) {
        results.push({ path: s.path, restored: "none", warnings: [`commit ${s.base.slice(0, 8)} is not in ${s.path}`] });
        continue;
      }
      await source.run(["worktree", "add", "--quiet", "--detach", "--", dest, s.base]);
    }
    const { branch: _branch, ...detached } = s;
    mapped.push(detached);
  }
  results.push(...(await restoreAttached(host, git.withCwd(worktree), thread, mapped, who)));
  return results;
}

/** Remove a worktree's checkouts of the attached repositories (git will not remove a worktree that has submodules). */
export async function removeCodeWorktrees(host: Host, git: Git, projectDir: string, worktree: string, force: boolean): Promise<void> {
  for (const { path } of await discoverAttached(host, git.withCwd(worktree))) {
    const source = git.withCwd(host.path.join(projectDir, path));
    try {
      await source.run(["worktree", "remove", ...(force ? ["--force"] : []), "--", host.path.join(worktree, path)]);
    } catch (e) {
      if (e instanceof Error && /is not a working tree/.test(e.message)) continue;
      throw e;
    }
  }
}

/**
 * Two worktrees have traded threads (`switchWorkspace`): trade the code to match. Each folder's repositories are put to the state
 * `attached.yml` now says there, after both are detached so a branch can move from one to the other.
 */
export async function tradeCode(
  host: Host,
  git: Git,
  sides: readonly { dir: string; thread: string }[],
  who: Identity,
): Promise<RestoreResult[]> {
  const all = await Promise.all(sides.map(async (s) => ({ ...s, ...(await recordedAttached(host, s.dir)) })));
  const results: RestoreResult[] = all.flatMap((a) => (a.problem === undefined ? [] : [a.problem]));
  for (const a of all)
    for (const s of a.states) {
      const repo = git.withCwd(host.path.join(a.dir, s.path));
      if ((await host.fs.stat(host.path.join(a.dir, s.path, ".git"))) !== undefined && (await repo.currentBranch()) !== undefined)
        await repo.detach();
    }
  const claimed = new Set<string>();
  for (const a of all) {
    const mapped: AttachedState[] = [];
    for (const s of a.states) {
      const repo = git.withCwd(host.path.join(a.dir, s.path));
      const branch =
        (await host.fs.stat(host.path.join(a.dir, s.path, ".git"))) === undefined ? undefined : await codeBranchFor(repo, s, claimed);
      const { branch: _was, ...rest } = s;
      mapped.push(branch === undefined ? rest : { ...rest, branch });
    }
    results.push(...(await restoreAttached(host, git.withCwd(a.dir), a.thread, mapped, who)));
  }
  return results;
}

// ---- merging the code of two threads (ADR 38) ------------------------------------------------------------------------------

export interface CodeSettings {
  /** A thread with no commits may merge its code like files. (A thread told to `share` always may.) */
  state: boolean;
  /** A thread with commits may be fast-forwarded into a parent that has nothing uncommitted. */
  rebase: boolean;
  /** What a branch made for a thread's commits is called: `<prefix>/<thread>`. */
  prefix: string;
}
export const CODE_DEFAULTS: CodeSettings = { state: true, rebase: true, prefix: "chattree" };

export interface CodeMergeInput {
  path: string;
  /** The thread being merged, as the receiving one last knew it (at the commit they diverged or were last merged). */
  before: AttachedState;
  /** The receiving thread now. */
  ours: AttachedState;
  /** The thread being merged now. */
  theirs: AttachedState;
  integrate: "share" | "thread" | "parent" | undefined;
  settings: CodeSettings;
  /** The receiving thread's branch (names the snapshot chain a merged state is added to). */
  ourThread: string;
  /** The merged thread's branch. */
  theirThread: string;
  /** The code in each thread's worktree, as paths a command can use. */
  ourDir: string;
  theirDir: string;
}

/** How the code of one attached repository came across. */
export type CodeOutcome =
  | { kind: "unchanged" }
  /** Merged as files are: the receiving thread's code is now `state`, uncommitted. */
  | { kind: "state"; state: AttachedState; conflicts: string[]; note: string }
  /** The receiving thread's branch (or detached HEAD) moved to the thread's commit. */
  | { kind: "fast_forward"; to: string; commits: number; note: string }
  /** Nothing changed in the receiving thread's code: its commits are on `branch` for it to integrate. */
  | { kind: "left"; branch: string; commits: number; note: string };

const quote = (p: string): string => (/^[A-Za-z0-9_./:@%+=,-]+$/.test(p) ? p : `"${p.replace(/(["\\$`])/g, "\\$1")}"`);
const short = (oid: string): string => oid.slice(0, 8);
const commitOf = (s: AttachedState): string => s.snapshot ?? s.base;

/** What a thread did to its code since `before`. */
export interface CodeFacts {
  hasCommits: boolean;
  hasUncommitted: boolean;
  /** The files are as they were (whatever the commits). */
  unchanged: boolean;
  /** The thread's HEAD is the receiving thread's HEAD or after it. */
  descends: boolean;
}

export async function codeFacts(repo: Git, i: Pick<CodeMergeInput, "before" | "ours" | "theirs">): Promise<CodeFacts> {
  const hasCommits = i.theirs.base !== i.before.base;
  const hasUncommitted = i.theirs.snapshot !== undefined;
  const unchanged = (await repo.treeOf(commitOf(i.theirs))) === (await repo.treeOf(commitOf(i.before)));
  const descends = i.theirs.base === i.ours.base || (await repo.isAncestor(i.ours.base, i.theirs.base));
  return { hasCommits, hasUncommitted, unchanged, descends };
}

/**
 * What stops the thread's code being merged, as a message with the commands that put it right; undefined when nothing does. The
 * thread's own side only (commits and uncommitted changes together; behind a parent that has nothing uncommitted), which is what the
 * thread itself can fix, so the thread's `merge` tool can check it before handing back.
 */
export function codeProblem(
  f: CodeFacts,
  i: Pick<CodeMergeInput, "path" | "before" | "ours" | "settings" | "integrate" | "theirDir">,
  oursClean: boolean,
): string | undefined {
  const dir = quote(i.theirDir);
  if (f.hasCommits && f.hasUncommitted)
    return (
      `The code in ${i.path} has commits and uncommitted changes, which cannot be merged together. Either commit the changes ` +
      `(git -C ${dir} add -A && git -C ${dir} commit -m "<what changed>") or fold the commits into uncommitted changes ` +
      `(git -C ${dir} reset ${short(i.before.base)}), then merge again.`
    );
  if (f.hasCommits && oursClean && i.settings.rebase && i.integrate !== "parent" && !f.descends) {
    const onto = i.ours.branch ?? short(i.ours.base);
    return (
      `The code in ${i.path} has commits, and the code it came from has moved on (it is at ${short(i.ours.base)}${i.ours.branch === undefined ? "" : ` on ${i.ours.branch}`}). ` +
      `Rebase yours onto it (git -C ${dir} rebase ${onto}), resolve any conflicts, and merge again.`
    );
  }
  return undefined;
}

const countCommits = async (repo: Git, from: string, to: string): Promise<number> =>
  Number((await repo.text(["rev-list", "--count", `${from}..${to}`], { readOnly: true })) || "0");

/**
 * Decide how one attached repository's code comes across in a merge, and prepare it (a commit for a merged state, a branch for the
 * commits left): nothing in the receiving thread's checkout is touched; `restoreAttached` does that afterwards. Throws `AttachedError`
 * with the commands to run when the thread's code is in a state that cannot be merged.
 *
 * Without commits, the code is merged as the files are: three ways, the state at `before` against the two states now, where both
 * changed the same file the receiving thread's version is kept. With commits and a receiving thread that has nothing uncommitted, it is
 * a fast-forward (the thread rebases first; `codeProblem` says so if it has not). Otherwise the commits are left on a branch, and the
 * receiving thread integrates them with ordinary git.
 */
export async function assessCode(host: Host, repo: Git, i: CodeMergeInput, who: Identity, date?: string): Promise<CodeOutcome> {
  const facts = await codeFacts(repo, i);
  const oursClean = i.ours.snapshot === undefined;
  const problem = codeProblem(facts, i, oursClean);
  if (problem !== undefined) throw new AttachedError(problem);

  if (!facts.hasCommits) {
    if (facts.unchanged) return { kind: "unchanged" };
    if (!(i.settings.state || i.integrate === undefined || i.integrate === "share"))
      throw new AttachedError(
        `Merging uncommitted code is turned off here (attached.merge.state): commit the changes in ${i.path} ` +
          `(git -C ${quote(i.theirDir)} add -A && git -C ${quote(i.theirDir)} commit -m "<what changed>") and merge again.`,
      );
    const merged = await repo.mergeTree(commitOf(i.ours), commitOf(i.theirs), { base: commitOf(i.before) });
    const tree =
      merged.conflictedPaths.length === 0
        ? merged.tree
        : await repo.rewriteTree(
            merged.tree,
            merged.conflictedPaths.map((path) => ({ path, from: commitOf(i.ours) })),
          );
    const { snapshot: _old, ...rest } = i.ours;
    if (tree === (await repo.treeOf(i.ours.base)))
      return { kind: "state", state: rest, conflicts: merged.conflictedPaths, note: stateNote(i, merged.conflictedPaths) };
    const ref = snapshotRef(i.ourThread);
    const tip = await repo.revParse(ref);
    const snapshot = await repo.commitTree(tree, tip === undefined ? [i.ours.base] : [i.ours.base, tip], {
      message: `chattree: the code of ${i.theirThread} merged into ${i.ourThread}`,
      author: who,
      committer: who,
      ...(date === undefined ? {} : { date }),
    });
    await repo.run(["update-ref", ref, snapshot]);
    return { kind: "state", state: { ...rest, snapshot }, conflicts: merged.conflictedPaths, note: stateNote(i, merged.conflictedPaths) };
  }

  const commits = await countCommits(repo, i.before.base, i.theirs.base);
  if (oursClean && i.settings.rebase && i.integrate !== "parent" && facts.descends) {
    const where = i.ours.branch === undefined ? "your checkout" : i.ours.branch;
    return {
      kind: "fast_forward",
      to: i.theirs.base,
      commits,
      note: `the ${commits} commit${commits === 1 ? "" : "s"} of the thread in ${i.path} were added to ${where}, which is now at ${short(i.theirs.base)}.`,
    };
  }

  // Left for the receiving thread: the commits need a branch to be found by.
  let branch = i.theirs.branch;
  if (branch === undefined) {
    const name = `${i.settings.prefix}/${i.theirThread}`;
    const tip = await repo.revParse(`refs/heads/${name}`);
    branch = tip === undefined || tip === i.theirs.base ? name : `${name}-${short(i.theirs.base)}`;
    await repo.run(["update-ref", `refs/heads/${branch}`, i.theirs.base]);
  }
  const ours = quote(i.ourDir);
  const why = !oursClean
    ? "you have uncommitted changes there"
    : !i.settings.rebase
      ? "merging commits automatically is turned off here (attached.merge.rebase)"
      : "it was asked to be left for you";
  const stash = oursClean
    ? ""
    : `Stash your uncommitted changes first (git -C ${ours} stash) and restore them after (git -C ${ours} stash pop). `;
  const onto = i.ours.branch ?? short(i.ours.base);
  return {
    kind: "left",
    branch,
    commits,
    note:
      `the ${commits} commit${commits === 1 ? "" : "s"} of the thread in ${i.path} are on the branch ${branch} and are not in your code yet (${why}). ${stash}` +
      `For a linear history rebase it (git -C ${quote(i.theirDir)} rebase ${onto}) and fast-forward (git -C ${ours} merge --ff-only ${branch}); ` +
      `or merge it as it is (git -C ${ours} merge ${branch}).`,
  };
}

function stateNote(i: CodeMergeInput, conflicts: readonly string[]): string {
  return (
    `the code changes of the thread in ${i.path} were merged into yours as uncommitted changes, as files are.` +
    (conflicts.length === 0 ? "" : ` Where both of you changed the same file yours was kept: ${conflicts.join(", ")}.`)
  );
}

/** The gitlinks (attached repositories) in a commit's tree, by path. */
export async function gitlinksAt(git: Git, rev: string): Promise<string[]> {
  const out = await git.run(["ls-tree", "-r", "-z", rev], { readOnly: true });
  return dec
    .decode(out.stdout)
    .split("\u0000")
    .filter((r) => r.startsWith("160000 "))
    .map((r) => r.slice(r.indexOf("\t") + 1));
}

/** The record as a commit holds it. */
export async function attachedAtRev(git: Git, rev: string): Promise<AttachedState[]> {
  const bytes = await git.readFileAt(rev, ATTACHED_FILE);
  return bytes === undefined ? [] : parseAttached(dec.decode(bytes));
}
